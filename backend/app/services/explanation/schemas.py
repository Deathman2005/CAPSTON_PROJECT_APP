"""Pydantic schemas for Explainable AI (XAI) detection explanations."""

from typing import List, Optional
from pydantic import BaseModel, Field
from app.ml.attribution import TokenSpan


class HindiExplanation(BaseModel):
    """Bilingual explanation payload in Hindi for localized user safety."""

    summary_title: str = Field(..., description="Short headline title in Hindi")
    why_flagged: str = Field(..., description="Detailed explanation of the risk in Hindi")
    recommended_actions: List[str] = Field(
        default_factory=list,
        description="List of actionable safety instructions in Hindi",
    )


class ExplanationResult(BaseModel):
    """Complete Explainable AI payload for SMS fraud and URL risk analysis."""

    summary_title: str = Field(
        ...,
        description="Concise, plain-language verdict headline (e.g., 'Fake KYC Verification Scam Detected')",
    )
    fraud_type: str = Field(
        ...,
        description="Identified fraud scenario code (e.g., 'fake_kyc_update', 'fake_upi_collect_request')",
    )
    why_flagged: str = Field(
        ...,
        description="Clear, accessible explanation of why this message or link was classified as risky or safe",
    )
    suspicious_factors: List[str] = Field(
        default_factory=list,
        description="Specific words, phrases, domains, or behavioral signals that triggered the verdict",
    )
    recommended_actions: List[str] = Field(
        default_factory=list,
        description="Step-by-step actionable safety advice for the user",
    )
    token_attributions: List[TokenSpan] = Field(
        default_factory=list,
        description="Character-offset token spans with signed attribution weights for UI highlighting",
    )
    top_risk_tokens: List[str] = Field(
        default_factory=list,
        description="Top tokens driving scam probability",
    )
    top_safe_tokens: List[str] = Field(
        default_factory=list,
        description="Top tokens driving safe assessment",
    )
    hindi: Optional[HindiExplanation] = Field(
        None,
        description="Optional Hindi localized explanation for accessibility",
    )
    model_used: str = Field(
        ...,
        description="Identifier of the model or template engine used (e.g. 'llama-3.3-70b-versatile' or 'deterministic_engine_v1')",
    )
    is_ai_generated: bool = Field(
        False,
        description="True if generated by Groq LLM; False if generated by deterministic rule fallback",
    )

